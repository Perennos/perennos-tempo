#[test]
fn undo_takes_the_last_edit_off_and_keeps_it() {
    let ctx = home("undo");
    let s = Session::create(&ctx, MODEL, Path::new("/w"), 5, None, 1_800_000_000).unwrap();
    let one = r#"{"n":1,"op":"scale","tensor":"a","params":{"cols":[1],"factor":3},"arrays":{},"touched":4}"#;
    let two = r#"{"n":2,"op":"ablate_direction","tensor":"a","params":{"columns":[0,1]},"arrays":{"vector":{"file":"deltas/0002_vector.npy","sha256":"x"}},"touched":2}"#;
    std::fs::write(s.dir.join("deltas/0002_vector.npy"), b"numbers").unwrap();
    std::fs::write(s.edits_file(), format!("{{\"edits\":[{one},{two}]}}")).unwrap();
    let before = s.edit_hash();
    let (_, text) = said(|o| show(&ctx, &s.id, o));
    assert!(
        text.contains("2 edits")
            && text.contains("ablate_direction on a (2 columns), 2 weights changed"),
        "{text}"
    );
    let (code, text) = said(|o| undo(&ctx, &s.id, true, 1, o));
    assert_eq!(code, 0);
    assert!(
        text.contains("Took off: ") && text.contains("ablate_direction"),
        "{text}"
    );
    assert_eq!(s.edits().len(), 1);
    assert_ne!(s.edit_hash(), before);
    // nothing is deleted: the edit and its numbers are still on disk
    assert!(std::fs::read_to_string(s.dir.join("undone.jsonl"))
        .unwrap()
        .contains("ablate_direction"));
    assert!(s.dir.join("deltas/0002_vector.npy").exists());
    assert!(s.undo_last().unwrap().is_some());
    assert_eq!(s.undo_last().unwrap(), None);
}

