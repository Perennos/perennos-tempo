// ---- the bench

fn bench_on<'a>(
    ctx: &'a Ctx,
    passes: u32,
    held: Option<&Path>,
) -> (Bench<'a>, std::rc::Rc<RefCell<Vec<String>>>) {
    let s = Session::create(
        ctx,
        MODEL,
        Path::new("/nowhere"),
        passes,
        held,
        1_800_000_000,
    )
    .unwrap();
    let calls = std::rc::Rc::new(RefCell::new(vec![]));
    struct Shared(std::rc::Rc<RefCell<Vec<String>>>);
    impl Helper for Shared {
        fn call(&mut self, tool: &str, args: &J) -> Result<J, String> {
            self.0
                .borrow_mut()
                .push(format!("{tool} {}", args.compact()));
            Ok(J::Obj(vec![("done".into(), J::Bool(true))]))
        }
    }
    (
        Bench {
            ctx,
            session: s,
            helper: RefCell::new(Box::new(Shared(calls.clone()))),
        },
        calls,
    )
}

fn jargs(s: &str) -> J {
    parse(s).unwrap()
}

#[test]
fn the_budget_is_enforced_and_survives_a_restart() {
    let ctx = home("budget");
    let (b, calls) = bench_on(&ctx, 3, None);
    let f = || jargs(r#"{"prompts":["a","b"],"max_tokens":8}"#);
    assert!(b
        .call("budget", &jargs("{}"))
        .unwrap()
        .contains("\"left\":3"));
    assert!(b
        .call("forward", &f())
        .unwrap()
        .contains("\"passes_left\":2"));
    // activation_diff runs two sets, so it costs two
    let d = jargs(r#"{"prompts_a":["a"],"prompts_b":["b"],"layer":2}"#);
    assert!(b
        .call("activation_diff", &d)
        .unwrap()
        .contains("\"passes_left\":0"));
    assert_eq!(calls.borrow().len(), 2);
    // out of passes: refused before the helper hears about it
    let e = b.call("forward", &f()).unwrap_err();
    assert!(e.contains("0 of 3 are left"), "{e}");
    assert_eq!(calls.borrow().len(), 2);
    // reads and edits still work with no passes left
    b.call("read_slice", &jargs(r#"{"tensor":"w","index":"0:2, 0:2"}"#))
        .unwrap();
    b.call(
        "set_slice",
        &jargs(r#"{"tensor":"w","index":"0:1, 0:1","values":[1]}"#),
    )
    .unwrap();
    assert_eq!(calls.borrow().len(), 4);
    // starting the bench again on the same session does not hand passes back
    let again = Session::open(&ctx, &b.session.id).unwrap();
    assert_eq!((again.used(), again.left()), (3, 0));
    assert!(again.charge(1).is_err());
}

