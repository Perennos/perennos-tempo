#[test]
fn rust_and_the_helper_edit_a_copy_and_leave_the_original_alone() {
    let Some(py) = python() else { return };
    let ctx = home("e2e");
    let model = root(&ctx).join("fake-model");
    std::fs::create_dir_all(&model).unwrap();
    let test_py = here().join("test_retune_bench.py");
    assert!(std::process::Command::new(py)
        .arg(&test_py)
        .arg("make-model")
        .arg(&model)
        .status()
        .unwrap()
        .success());
    let file = model.join("model.safetensors");
    let before = crate::setup::sha256::sha256_hex(&std::fs::read(&file).unwrap());
    let s = Session::create(&ctx, MODEL, &model, 2, None, NOW).unwrap();
    let argv: Vec<String> = [
        py,
        test_py.to_str().unwrap(),
        "serve-fake",
        model.to_str().unwrap(),
        s.dir.to_str().unwrap(),
    ]
    .map(String::from)
    .to_vec();
    let helper = PyHelper::spawn(&argv, &s.dir.join("helper.log")).unwrap();
    let b = Bench {
        ctx: &ctx,
        session: s.clone(),
        helper: RefCell::new(Box::new(helper)),
    };
    let loud = b
        .call("forward", &jargs(r#"{"prompts":["a","b"],"max_tokens":8}"#))
        .unwrap();
    assert!(loud.contains("\"loop_pct\":100"), "{loud}");
    let r = b
        .call(
            "set_slice",
            &jargs(r#"{"tensor":"mlp.down","index":"0:1, 0:1","values":[0.1]}"#),
        )
        .unwrap();
    assert!(r.contains("\"edit\":1"), "{r}");
    let r = b
        .call(
            "ablate_direction",
            &jargs(r#"{"tensor":"mlp.down","vector":[1,2,-1,0.5],"columns":[1,3]}"#),
        )
        .unwrap();
    assert!(r.contains("\"weights_changed\""), "{r}");
    // the helper says no, and the bench says it as an error
    let e = b
        .call(
            "read_slice",
            &jargs(r#"{"tensor":"mlp.down","index":"0:9, 0:2"}"#),
        )
        .unwrap_err();
    assert!(e.contains("outside"), "{e}");
    // the edit took effect in the forward pass, and the budget counted both
    let quiet = b
        .call("forward", &jargs(r#"{"prompts":["a","b"],"max_tokens":8}"#))
        .unwrap();
    assert!(
        quiet.contains("\"loop_pct\":0") && quiet.contains("\"passes_left\":0"),
        "{quiet}"
    );
    assert!(b
        .call("forward", &jargs(r#"{"prompts":["a"]}"#))
        .unwrap_err()
        .contains("0 of 2 are left"));
    assert_eq!(s.edits().len(), 2);
    assert_eq!(
        crate::setup::sha256::sha256_hex(&std::fs::read(&file).unwrap()),
        before
    );
    // undo, then the same tensor reads as the original again
    let read = |b: &Bench| {
        b.call(
            "read_slice",
            &jargs(r#"{"tensor":"mlp.down","index":"0:4, 0:6"}"#),
        )
        .unwrap()
    };
    let edited = read(&b);
    s.undo_last().unwrap();
    s.undo_last().unwrap();
    assert_ne!(read(&b), edited);
    assert!(b
        .call(
            "read_slice",
            &jargs(r#"{"tensor":"mlp.down","index":"0:1, 0:1"}"#)
        )
        .unwrap()
        .contains("2.0"));
    assert_eq!(
        crate::setup::sha256::sha256_hex(&std::fs::read(&file).unwrap()),
        before
    );
}
