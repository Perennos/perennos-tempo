fn home(tag: &str) -> Ctx {
    static N: std::sync::atomic::AtomicU32 = std::sync::atomic::AtomicU32::new(0);
    let d = std::env::temp_dir().join(format!(
        "tempo-retune-{tag}-{}-{}",
        std::process::id(),
        N.fetch_add(1, std::sync::atomic::Ordering::SeqCst)
    ));
    std::fs::create_dir_all(&d).unwrap();
    Ctx {
        home: d.clone(),
        agent_data: d.join("agent"),
        vault: d.join("vault"),
        bin_dirs: vec![],
        browser: false,
        opened: Default::default(),
    }
}

const MODEL: &str = "qwen3.5:0.8b";

/// Runs nothing: writes down what it was asked, and answers the helper's `apply` like the helper.
#[derive(Default)]
struct RecExec {
    log: RefCell<Vec<Vec<String>>>,
    fail_on: RefCell<Option<String>>,
}

impl Exec for RecExec {
    fn run(&self, _t: &Target, argv: &[String], _l: Duration) -> Result<Done, String> {
        self.log.borrow_mut().push(argv.to_vec());
        let line = argv.join(" ");
        if self
            .fail_on
            .borrow()
            .as_ref()
            .is_some_and(|f| line.contains(f.as_str()))
        {
            return Ok(Done {
                ok: false,
                tail: "it broke (made up)".into(),
            });
        }
        let tail = if line.contains(" apply ") {
            "loading\n{\"changed\": 131072, \"total\": 819200000, \"tensors\": {}}".into()
        } else {
            String::new()
        };
        Ok(Done { ok: true, tail })
    }
    fn put(&self, t: &Target, name: &str, text: &str) -> Result<(), String> {
        std::fs::create_dir_all(&t.dir).unwrap();
        std::fs::write(Path::new(&t.dir).join(name), text).unwrap();
        Ok(())
    }
    fn get(&self, _t: &Target, _n: &str, _to: &Path) -> Result<(), String> {
        Err("not used".into())
    }
}

impl RecExec {
    fn ran(&self, needle: &str) -> usize {
        self.log
            .borrow()
            .iter()
            .filter(|a| a.join(" ").contains(needle))
            .count()
    }
}

/// The base loops on every held-out answer; the retuned model answers right and does not loop.
struct LoopGen {
    tuned_breaks_canary: bool,
}

impl Gen for LoopGen {
    fn answer(&self, model: &str, m: &[(String, String)]) -> Result<String, String> {
        let q = m.last().map(|x| x.1.as_str()).unwrap_or("");
        let tuned = model.contains("retune-try");
        if let Some((_, any)) = eval::CANARY.iter().find(|(p, _)| *p == q) {
            return Ok(if tuned && self.tuned_breaks_canary {
                "no idea".into()
            } else {
                any[0].to_string()
            });
        }
        Ok(if tuned {
            format!("Answer for {q}, long enough to keep around.")
        } else {
            "wait let me think about it again so ".repeat(8)
        })
    }
}

fn machine(ram: f64, gpu: Option<f64>) -> Machine {
    Machine {
        name: "this computer".into(),
        at: Where::Local,
        ram_gb: ram,
        cpus: 8,
        gpu: gpu.map(|g| ("A card".into(), g)),
    }
}

fn deps<'a>(
    e: &'a RecExec,
    g: &'a dyn Gen,
    mf: &'a dyn Fn(&str) -> Option<String>,
    machines: Vec<Machine>,
) -> Deps<'a> {
    Deps {
        exec: e,
        gen: g,
        machines,
        modelfile_of: mf,
        exe: "/opt/tempo/tempo-launch".into(),
        windows: false,
    }
}

fn base_modelfile(_: &str) -> Option<String> {
    Some("# Modelfile generated by ollama\nFROM /root/.ollama/blobs/sha256-abc\nTEMPLATE \"\"\"{{ .Prompt }}\"\"\"\nPARAMETER stop <|im_end|>\n".into())
}

fn said(f: impl FnOnce(&mut dyn Write) -> i32) -> (i32, String) {
    let mut v = vec![];
    let c = f(&mut v);
    (c, String::from_utf8(v).unwrap())
}

fn accept_terms(ctx: &Ctx) {
    write_atomic(&root(ctx).join("terms.json"), br#"{"accepted": true}"#).unwrap();
}

fn fake_weights(ctx: &Ctx) -> PathBuf {
    let w = root(ctx).join("weights").join("qwen3-5-0-8b");
    std::fs::create_dir_all(&w).unwrap();
    std::fs::write(w.join("model.safetensors"), b"not real").unwrap();
    w
}

fn make_venv(ctx: &Ctx) {
    let p = py(ctx, false);
    std::fs::create_dir_all(Path::new(&p).parent().unwrap()).unwrap();
    std::fs::write(&p, "").unwrap();
}

