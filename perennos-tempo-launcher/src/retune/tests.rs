const NOW: u64 = 1_800_000_000; // 2027-01-15

#[test]
fn a_retune_that_stops_the_looping_is_checked_promoted_and_recorded() {
    let ctx = home("check");
    let s = ready_session(&ctx);
    let (e, g) = (
        RecExec::default(),
        LoopGen {
            tuned_breaks_canary: false,
        },
    );
    let d = deps(&e, &g, &base_modelfile, vec![machine(32.0, None)]);
    // asked first, and a no changes nothing
    let (code, text) = said(|o| {
        check(
            &ctx,
            &d,
            &s.id,
            None,
            "q8_0",
            false,
            NOW,
            &mut |q| {
                assert_eq!(q, "Go? [y/N] ");
                false
            },
            o,
        )
    });
    assert_eq!(code, 0);
    assert!(text.contains("Not started. Nothing was changed.") && e.log.borrow().is_empty());
    // yes
    let (code, text) = said(|o| check(&ctx, &d, &s.id, None, "q8_0", false, NOW, &mut |_| true, o));
    assert_eq!(code, 0, "{text}");
    assert!(
        text.contains("131072 of 819200000 weights changed (0.0160%)"),
        "{text}"
    );
    assert!(
        text.contains("qwen3.5:0.8b loops on 40% of answers. A retune might fix that"),
        "{text}"
    );
    assert!(
        text.contains("It passed:") && text.contains("Loops: 40% to 0%"),
        "{text}"
    );
    // the steps ran in order: apply, convert, create the scoring copy, create the model
    let log = e.log.borrow();
    let order: Vec<usize> = [
        "apply",
        "convert_hf_to_gguf.py",
        "retune-try",
        "tempo-qwen3-5-0-8b-retuned-20270115",
    ]
    .iter()
    .map(|n| {
        log.iter()
            .position(|a| a.join(" ").contains(n))
            .unwrap_or_else(|| panic!("{n} did not run: {log:?}"))
    })
    .collect();
    assert!(order.windows(2).all(|w| w[0] < w[1]), "{order:?}");
    let conv = log[order[1]].join(" ");
    assert!(
        conv.contains("--outtype q8_0") && conv.contains("--outfile model.gguf"),
        "{conv}"
    );
    // the Modelfile kept the base's template and none of its weights
    let mf = std::fs::read_to_string(s.dir.join("work/check-1/Modelfile")).unwrap();
    assert!(
        mf.starts_with("FROM ./model.gguf\n")
            && mf.contains("TEMPLATE")
            && mf.contains("PARAMETER stop")
            && !mf.contains("sha256-abc")
            && !mf.contains('#'),
        "{mf}"
    );
    // the manifest says what was edited and how it scored
    let m = versions::list(&ctx, MODEL).pop().unwrap();
    assert_eq!(
        (m.status.as_str(), m.model.as_str()),
        ("promoted", "tempo-qwen3-5-0-8b-retuned-20270115")
    );
    assert_eq!(m.edit_hash, s.edit_hash());
    assert_eq!((m.changed, m.total, m.edits), (131_072, 819_200_000, 1));
    assert!((m.percent() - 0.016).abs() < 1e-9);
    assert_eq!(m.base_scores.as_ref().unwrap().loops, 40.0);
    assert_eq!(m.tuned_scores.as_ref().unwrap().loops, 0.0);
    assert!(m.passed());
    assert_eq!(
        versions::active(&ctx, MODEL).unwrap().1,
        "tempo-qwen3-5-0-8b-retuned-20270115"
    );
    let (_, v) = said(|o| versions_cmd(&ctx, None, o));
    assert!(
        v.contains("(playing)")
            && v.contains("passed")
            && v.contains("131072 of 819200000 weights (0.0160%)")
            && v.contains("loops 40% to 0%"),
        "{v}"
    );
}

