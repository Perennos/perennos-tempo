#[test]
fn the_terms_are_said_asked_once_and_remembered() {
    let ctx = home("terms");
    let (e, g) = (
        RecExec::default(),
        LoopGen {
            tuned_breaks_canary: false,
        },
    );
    let d = deps(&e, &g, &base_modelfile, vec![machine(32.0, None)]);
    let w = fake_weights(&ctx);
    let plan_with = |yes: bool, answer: bool, asked: &mut Vec<String>| {
        let cmd = RetuneCmd::Plan {
            model: MODEL.into(),
            hf: None,
            weights: Some(w.clone()),
            yes,
        };
        said(|o| {
            run_with(
                &ctx,
                cmd,
                &d,
                1_800_000_000,
                &mut |q| {
                    asked.push(q.into());
                    answer
                },
                o,
            )
        })
    };
    // no: nothing is set up, and `--yes` does not answer this one for you
    let mut asked = vec![];
    let (code, text) = plan_with(true, false, &mut asked);
    assert_eq!(code, 0);
    assert!(text.contains(
        "Anthropic's consumer terms bar using the service to develop or train competing AI models"
    ));
    assert!(text.contains("it's your call: check your plan's terms"));
    assert_eq!(asked.len(), 1);
    assert!(!terms_ok(&ctx));
    assert!(e.log.borrow().is_empty());
    // the bench will not start without it
    let err = bench_session(&ctx, MODEL, 50, Some(&w), None, None, false, 1).unwrap_err();
    assert!(err.contains("retune plan"), "{err}");
    // yes: asked once, remembered
    let mut asked = vec![];
    let (_, text) = plan_with(true, true, &mut asked);
    assert_eq!(asked[0], "Go on? [y/N] ");
    assert!(terms_ok(&ctx) && text.contains("Licence: Apache-2.0"));
    let mut asked = vec![];
    let (_, text) = plan_with(true, false, &mut asked);
    assert!(
        asked.is_empty() && !text.contains("consumer terms"),
        "{text}"
    );
}

